                    =========== Grid Terminology ===============
Sebelum kita lanjut tentang Grid Container, kita akan bahas dulu mengenai Grid Terminology agar tidak bingung di materi selanjutnya.
Seperti yang kita tahu, bentuk dari Grid itu serupa dengan tabel.

                    =========== Grid Container ===============
Grid Container merupakan kompomenet yang menggunakan display: grid;.
Mirip dengan Flex Container, yang dimana menggunakan display: flex;.

                    =========== Grid Item ===============
Grid Item merupakan komponen Children atau anakan langsung dari Grid Container.

                    =========== Grid Line ===============
Grid Line merupakan garis pemisah dalam grid, baik itu secara hirizontal maupun secara vertikal.

                    =========== Grid Cell ===============
Grid Cell merupakan luas area yang terdapat di dalam kolom dan baris yang dipisahkan oleh Grid Line.

                    =========== Grid Track ===============
Grid Track merupakan bagian luas area antara dua Grid Line, baik itu secara vertikal maupun horizontal.

                    =========== Grid Area ===============
Grid Area merupakan total luas area dari beberapa Grid Cell.