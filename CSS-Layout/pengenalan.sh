                    =========== Pengenalan CSS Layout ===============
Di materi CSS Dasar, kita sudah belajar bagaimana menambahkan gaya pada element-element di HTML.
Selain menambahkan gaya di element, CSS juga biasanya digunakan untuk membuat layout (tata letak) halaman web.
Hampir semua web di dunia akan menggunakan CSS untuk melakukan layouting (tata letak) komponen HTML nya.
Salah satu tujuan melakukan tata letak adalah agar tampilan halaman web lebih menarik.

                    =========== Jangan Gunakan Tabel untuk Layout ===============
Terkadang mungkin ada beberapa pengembang web menggunakan Tabel untuk membuat tata letak, karena dianggap lebih mudah.
Namun, hal tersebut sangat tidak disarankan untuk menggunakan tabel, terutama pada kondisi layout yang sangat kompleks, maka akan menyulitkan.

