                    =========== Audio ===============
Selain gambar, video, HTML juga mendukung untuk audio.
Untuk audio, kita dapat menggunakan tag audio.
Cara penggunaannya serupa dengan tag video, didalamnya kita dapat tambahkan tag source.

Contoh kode:
<html>
    <head>
        <title>Belajar Tag Audio HTML Dasar</title>
    </head>
    <body>
        <h1><b>Belajar Tag Audio HTML Dasar</b></h1>
        <audio controls>
            <source src="sample.mp3">
        </audio>
    </body>
</html>