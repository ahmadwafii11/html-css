                    =========== Computer Code ===============
Sebagai programmer, terkadang kita sering membuat web artikel tentang kode program.
Pada kasus seperti ini, ketika kita membuat kode program di HTML menggunakan paragraph, maka akan menyulitkan, karena semua enter dan spasi akan dinormalkan oleh HTML.
Kadang kita ingin menampilkan kode apa adanya.

                    =========== Tag Pre ===============
Untuk menampilkan tulisan di dalam HTML apa adanya, kita dapat menggunakan tag pre.
Namun, perlu diingat kode HTML tetap tidak akan ditampilkan.
Jadi, kita harus menggunakan HTML Entities.

Contoh kode:
<html>
    <body>
        <h1>Bekajar Kode Python</h1>

        <pre>
print("Hello World")
        </pre>
    </body>
</html>