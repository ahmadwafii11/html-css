                    =========== Comment ===============
Comment atau komentar merupakan sebuah informasi tambahan di HTML, yang tidak akan ditampilkan di halaman Web Browser.
Komentar biasanya digunakan untuk menambahkan informasi tambahan untuk pengembang Web, jadi bukan tujuan untuk ditampilkan di halaman Web.
Untuk membuat komentar kita dapat menggunakan:
<!--isi komentar-->
Semua isi yang terdapat di dalam komentar tidak akan ditampilkan di Web Browser, termasuk tag HTML.

contoh kode:
<html>
    <body>
        <h1>Day 1 Belajar HTML Dasar</h1>
        <!--<p>Ini adalah komentar yang tidak akan muncul di halaman Web Browser</p>-->
        <p>Ini paragraf yang akan muncul di halaman Web Browser</p>
    </body>
</html>