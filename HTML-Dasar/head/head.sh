                    =========== Head ===============
Selain tag body, di HTML juga terdapat tag head.
Tag head dapat digunakan untuk menambahkan informasi yang tidak dimunculkan di halaman web.
Head biasanya digunakan untuk menambahkan informasi seperti CSS atau JavaScript.
Head juga bisa digunakan untuk menambahkan metadata (informasi tambahan) untuk halaman HTML, biasanya digunakan oleh Search Engine misalnya.

                    =========== Title ===============
Di dalam Head, kita juga dapat menambahkan tag title yang dapat digunakan untuk mengubah judul halaman di Web Browser.

Contoh kode:
<html>
    <head>
        <title>Belajar Head HTML</title>
        <meta name="author" content="Ahmad Wafi Fathurrahman">
        <meta name="keywords" content="Python, HTML, CSS, JavaScript">
        <meta name="description" content="Belajar HTML Dasar">
        <!--meta ini digunakan oleh Web Browser untuk menambahkan informasi mengenai halaman HTML yang kita buat-->
    </head>
    <body>
        <h1><b>Belajar HTML Head</b></h1>
    </body>
</html>