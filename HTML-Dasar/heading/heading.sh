                    =========== Heading ===============
Saat kita membuat dokumen atau buku, biasanya terdapat Heading.
Heading merupakan kata-kata yang mendeskripsikan isi dari tulisan yang telah kita buat.
Seperti judul, tapi untuk bagian tulisannya.
Contoh ketika kita melihat buku, Heading sering digunakan untuk tulisan Bab
Di HTML, kita dapat membuat Heading dengan tag h.

                    =========== Tingkatan Heading ===============
Heading memiliki tingkatan, yang paling tinggi adalah tingkatan 1, selanjutnya tingkatan 2, 3 dan seterusnya.
Yang membedakan biasanya adalah ukuran hurufnya yang akan semakin mengecil.
Di HTML, kita dapat menggunakan tag h1, h2, h3 dan seterusnya untuk menemtukan tingkatan Heading.
HTML sendiri mendukung Heading sampai ke tingkatan 6.