                    =========== Web ===============
Saat ini web digunakan oleh jutaan, bahkan mungkin milyaran orang setiap hari.
Dengan web, kita dapat melakukan belajar online, mendengarkan musik online, menonton video online, belanja online, hingga memesan makanan secara online
Namun, perlu diperhatikan, Web bukanlah Internet.

                    =========== Internet ===============
Internet merupakan mekanisme komunikasi antar komputer.
Awal internet ada, untuk komunikasi antar komputer, kita membutuhkan jaringan kabel telepon.
Namun sekarang, semenjak maraknya jaringan Wifi dan sejenisnya, komunikasi antar komputer menjadi lebih cepat dan mudah.

                    =========== Web ===============
Web merupakan kumpulan informasi yang tersedia dalam sebuah komputer yang terkoneksi secara terus menerus melalui internet.
Web bisa berisi informasi dalam bentuk apapun, seperti teks, gambar, audio, video dll.
Web berjalan di aplikasi yang bernama Web Server, yakni aplikasi yang digunakan untuk menyimpan dan menyampaikan isi informasi dari Web.

                    =========== Domain ===============
Saat komputer Web terhubung ke internet, biasanya dia memiliki suatu alamat.
Alamat tersebut dinamakan ip address, yang memiliki format misalnya seperti 172.217.194.94
Karena alamat ip address sangat sulit untuk diingat, maka dibuatlah DOMAIN.
Nama domain merupakan alamat yang bisa digunakan sebagai alias ke ip address.
Contoh domain misalnya seperti google.com, facebook.com, youtube.com, amazon.com, dll.
Dengan nama domain, kita sebagai manusia dapat lebih mudah untuk mengingat dibandingkan dengan alamat ip address.
Namun, saat kita menggunakan nama domain, sebenarnya komputer kita masih tetap akan mengakses web menggunakan alamat ip address.

                    =========== Web Browser ===============
Jika Web Server merupakan aplikasi yang digunakan untuk menyimpan informasi Web.
Maka, Web Browser merupakan aplikasi yang digunakan untuk mengakses Web melalui internet.
Kita bisa saja mengakses Web secara langsung tanpa bantuan Web Browser, namun Web Server hanya akan memberikan informasi bahasa mesin seperti HTML, JavaScript, CSS, Gambar, Video, dll.
Dengan menggunakan Web Browser, semua bahasa mesin tersebut dapat ditampilkan secara visual sehingga kita dapat menyerap informasinya dengan lebih mudah.