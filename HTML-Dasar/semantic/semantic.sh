                    =========== Semantic ===============
Semantic element merupakan element yang memiliki arti.
Sebelum HTML 5, setiap kita ingin membuat layout di HTML, kita biasanya hanya menggunakan tag div dan tag span.
Hal tersebut terkadang tidak memiliki arti.
Di HTML 5, terdapat tag-tag seperti div dan span, namun memiliki arti.
Oleh karena itu, kita direkomendasikan menggunakna semantic tag agar kode HTML yang kita buat lebih mudah untuk dibaca dan dimengerti orang lain.

                    =========== Semantic Tag ===============
- Tag article, digunakan untuk konten artikel
- Tag aside, digunakan untuk bagian disamping konten, semisal kayak sidebar
- Tag figure, digunakan untuk konten ilustrasi, diagram, foto, dll.
- Tag figurecaption, digunakan untuk keterangan tag figure
- Tag footer, digunakan untuk bagian footer dokumen
- Tag header, digunakan untuk untuk bagian header dokumen
- Tag main, digunakan untuk konten utama dokumen
- Tag mark, digunakan untuk bagian yang ditandai atau highlight
- Tag nav, digunakan untuk bagian navigasi link
- Tag section, digunakan untuk section di dokumen
- Tag details, digunakan untuk bagian yang lebih detail yang bisa pengguna lihat
- Tag summary, digunakan untuk heading untuk tag details
- Tag time, digunakan untuk konten waktu / tanggal

