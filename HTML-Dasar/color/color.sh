                    =========== Color ===============
HTML mendukung format penulisan warna tidak hanya dengan nama warnanya (red, blue, green, dll.), namun juga dengan format penulisan warna seperti HEX, RGB, HSL, dll.
Dengan begitu, penulisan warna menjadi lebih akurat dibandingkan dengan nama warnanya saja.

                    =========== Color Picker ===============
Salah satu website yang dapat kita gunakan dalam memilih warna adalah:
https://colorpicker.me/
Dalam website tersebut, kita dapat mencari warna yang kita inginkan dan menyalin kode Hex untuk warna tersebut.

contoh kode:
<html>
    <body>
        <p style="background-color: #da18d6;">Ini adalah paragraf dengan background color format Hex</p>
        <p style="background-color: rgb(26, 217, 24);">Ini adalah paragraf dengan background color format RGB</p>
        <p style="background-color: hsl(226, 80%, 47%);">Ini adalah paragraf dengan background color format HSL</p>
    </body>
</html>