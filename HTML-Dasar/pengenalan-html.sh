                    =========== Pengenalan HTML ===============
HTML merupakan singkatan dari HyperText Markup Language.
HTML bukanlah sebuah bahasa pemrograman, karena HTML sendiri adalah sebuah format dasar yang digunakan untuk membuat halaman web.
HTML adalah struktur dasar dari halaman web.
HTML mendeskripsikan struktur dari isi konten halaman Web.
Selain HTML, terdapat hal lain untuk mendeskripsikan sebuah halaman web, seperti untuk gaya tampilan halaman web menggunakan CSS atau interaksi halaman menggunakan JavaScript.
HTML sendiri sebenarnya adalah sekumpulan kode yang berisikan informasi halaman web.
Kode HTML akan dibaca oleh Web Browser untuk ditampilkan secara visual.

                    =========== Kode HTML ===============
Untuk melihat kode HTML, kita dapat membuka website yang kita mau menggunakan Web Browser.
Lalu, gunakan menu View Source di aplikasi Web Browsernya.

                    =========== Tag ===============
Kode HTML berisikan kumpulan tag-tag yang kita buat.
Tag adalah perintah dalam HTML yang memiliki aturan pembuka dan penutup.
Terdapat banyak sekali tag di HTML.
Contoh untuk membuat tulisan paragraf di HTML, kita dapat menggunakan tag p, yag dimana penulisannya:
<p> Ahmad Wafi Fathurrahman </p>
<p> diawal adalah tag pembuka
</p> diakhir adalah tag penutup. dan Ahmad Wafi Fathurrahman merupakan isi konten dari tag p.
Tag berisi kontennya bisa kita sebut dengan nama Element.

                    =========== Void Element ===============
Pada beberapa kasus, terdapat tag di HTML yang tidak perlu memiliki isi konten
Hal ini dapat kita sebut dengan Void Element.
Contoh Void Element:
Di HTML terdapat Tag untuk membuat Break Line / Enter, dengan menggunakan tag br.
Karena tag br tidak memiliki konten, maka kita dapat menggunakan perintah:
<br> atau </br>
Tanpa harus menggunakan tag pembuka dan tag penutup.

                    =========== Attribute ===============
Element memiliki atribut. 
Attribute merupakan informasi tambahan untuk tag yang kita gunakan.
Contoh, untuk menampilkan gambar di HTML, kita dapat menggunakan tag <img> dengan atribut src yang berisikan lokasi gambar yang ingin kita tampilkan.
Contoh kode:
<img src="lokasi/gambar/nama_file.jpg"/>
Attribute dapat digunakan di Element biasa atau di Void Element.

                    =========== HTML Tidak Case Sensitive ===============
Penulisan tag di HTML tidak case sensitive, artinya huruf besar atau kecil tidak masalah.
Namun, sangat disarankan menggunakan huruf kecil semua semisal <p>, bukan <P>.