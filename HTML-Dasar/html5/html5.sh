                    =========== HTML5 ===============
Pada tahun 2008, HTML sudah rilis  versi 5.
Terdapat banyak perubahan yang terjadi di HTML 5 dari versi sebelumnya HTML 4, terutama dari interaksi yang lebih kaya (perlu menggunakan JavaScript).
Dahulu, ketika ingin membuat web yang interaktif, kebanyakan orang menggunakan Adobe Flash, namun sekarang cukup menggunakan HTML 5, CSS dan JavaScript sudah dapat dilakukan.
HTML 5 membawa struktur baru pada kerangka pembuatan halaman HTML.
Struktur HTML 5:
<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>Document</title>
</head>
<body>
    
</body>
</html>

Untuk memunculkan default template HTML 5 seperti diatas, ketik saja "html:5" di vscode.
