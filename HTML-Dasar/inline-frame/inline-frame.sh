                    =========== Inline Frame ===============
Pada saat membuat halaman web, terkadang kita ingin menampilkan halaman web lain pada halaman tersebut.
Pada kasus seperti itu, kita dapat menggunakan Inline Frame.
Inline Frame di HTML dapat menggunakan tag iframe.
Inline Frame sangat banya digunakan oleh banyak website.
Seperti contohnya di Youtube yang menggunakan Inline Frame ketika kita ingin menampilkan video Youtube di website kita.

Contoh kode:
<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>Belajar Inline Frame HTML Dasar</title>
</head>
<body>
    <h1><b>Belajar Inline Frame HTML Dasar</b></h1>
    <iframe src="color.html" frameborder="1" height="500px" width="1000px"></iframe>
</body>
</html>