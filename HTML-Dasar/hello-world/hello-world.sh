                    =========== Hello World ===============
Salah satu kebiasaan pengembanh Web ketika pertama kali belajar, adalah membuat halaman Hello World.
Halamannya sederhana, hanya berisikan tulisan Hello World saja.

                    =========== Tag Body ===============
Struktur HTML, dimulai dari menggunakan tag html. 
Dalam tag HTML, terdapat tag body.
Dalam tag body, kita dapat memasukkan tag apapun termasuk tulisan yang nanti secara otomatis akan ditampilkan di halaman web oleh aplikasi Web Browser.