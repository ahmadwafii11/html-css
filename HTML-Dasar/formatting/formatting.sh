                    =========== Formatting ===============
Dalam aplikasi pengolahan teks seperti Microsoft Word, kita dapat mengubah format tulisan menjadi tebal atau miring misalnya.
Begitu juga di HTML, kita dapat menambahkan formatting di text yang ingin kita tampilkan menggunakan tag yang sesuai dengan format yang kita mau.

                    =========== Formatting Tag ===============
<b>, <strong> untuk tebal / bold
<i>, <em> untuk italic / miring
<small> untuk teks kecil
<del> untuk teks dicoret
<ins> untuk teks dengan garis bawah
<sub> untuk subscript teks
<sup> untuk superscript teks

Contoh kode:
<html>
    <body>
        <h1><b>Formatting</b> Tag: </h1>
        <p><b>Ini paragraf untuk tag b</b></p>
        <p><strong>Ini paragraf untuk tag strong</strong></p>
        <p><i>Ini paragraf untuk tag i</i></p>
        <p><small>Ini paragraf untuk tag small</small></p>
        <p><del>Ini paragraf untuk tag del</del></p>
        <p><ins>Ini paragraf untuk tag ins</ins></p>
        <p>teks biasa<sub>Ini paragraf untuk tag sub</sub></p>
        <p>teks biasa<sup>Ini paragraf untuk tag sup</sup></p>
    </body>
</html>