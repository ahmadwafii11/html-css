                    =========== Emoji ===============
Di dalam website, kita sering kali melihat emoji pada tulisan.
Bagaimana cara membuat emoji di HTML?
HTML sudah memiliki standar untuk membuat emoji, mirip dengan HTML Entities, kita juga dapat menggunakan kode untuk membuat Emoji.
Kita dapat melihat daftar emoji yang dapat kita gunakan melalui:
https://www.quackit.com/character_sets/emoji/emoji_v3.0/unicode_emoji_v3.0_characters_all.cfm

Contoh kode:
<html>
    <body>
        <h1><b>Belajar Emoji HTML</b></h1>
        <p>Hello &#x1F923; &#x1F61A; &#x1F633;</p>
    </body>
</html>
