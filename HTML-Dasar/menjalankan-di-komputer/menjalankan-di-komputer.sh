                    =========== Menjalankan di Komputer ===============
Sebelumnya kita telah coba membuka file HTML hello-world.html menggunakan Web Browser.
Namun, cara seperti itu bukanlah hal baik, karena nanti akan ada beberapa fitur di HTML yang tidak berfungsi.
Oleh karena itu, disarankan untuk menjalankan Web yang kita buat menggunakan aplikasi Web Server.

                    =========== Live Server ===============
Aplikasi Web Server sebenarnya banyak sekali, namun kita akan menggunakan yang paling mudah dengan sebuah extension di Visual Studio Code.
Kita dapat menginstall extension bernama Live Server yang dapat digunakan untuk menjalankan Web Server dari Visual Studio Code secara mudah.