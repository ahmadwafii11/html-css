                    =========== Favicon ===============
Saat kita membuka website seperti Google, Facebook, Netflix atau yang lainnya, biasanya pada bagian tab Web Browser terdapat logo perusahaannya.
Bagaimana cara membuatnya? 
Itu merupakan fitur favicon di HTML.

                    =========== Tag Link ===============
Untuk membuat favicon, kita dapat menggunakan tag link pada bagian head.
Yang dimana dalam link tersebut kita perlu menggunakan atribut rel="icon" dan href menuju lokasi gambar icon.
Gambar icon dapat berupa file ico, png, jpg, svg, atau gif.

