                    =========== Unordered List (ul) ===============
Untuk membuat daftar tulisan, kita dapat menggunakan tag ul di HTML.
Setiap daftar isinya, kita dapat menggunakan tag li.

Contoh kode:
<html>
    <body>
        <h2>My Hobby:</h2>
        <ul>
            <li>Ngoding PHP</li>
            <li>Maen FM</li>
            <li>Nonton MU</li>
            <li>Menghina Liverpool</li>
        </ul>
    </body>
</html>

                    =========== Oredered List (ol) ===============
Jika kita ingin membuat daftar list yang berurutan (memiliki angka), maka kita dapat mengganti tag ul menjadi ol.
Untuk daftar isinya tetap sama menggunakan tag li.

Contoh kode:
<html>
    <body>
        <h2>My Bini: </h2>
        <ol>
            <li>Waguri</li>
            <li>Mikasa Ackerman</li>
            <li>Ini list dengan ol (ordered list)</li>
        </ol>
    </body>
</html>

                   =========== Oredered List Type ===============
Pada kasus ketika kita ingin menggunakan daftar yang berurutan (ol), kita dapat mengubah format daftarnya. 
Defaultnya menggunakan angka (dimulai dari 1).
Kita dapat menambahkan attribute type di ol dengan nilai: 
type="1", artinya dafatar isi akan menggunakan angka (ini adalah default dari ol (ordered list)).
type="A", artinya dafatar isi akan menggunakan huruf kapital.
type="a", artinya dafatar isi akan menggunakan huruf kecil.
type="I", artinya dafatar isi akan menggunakan angka romawi kapital.
type="i", artinya dafatar isi akan menggunakan angka romawi kecil.