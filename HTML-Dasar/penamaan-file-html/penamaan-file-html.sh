                    =========== Penamaan File HTML ===============
Sebenarnya tidak terdapat aturan khusus dalam pembuatan nama file untuk HTML.
Kita dapat menggunakan nama file apapun, dan huruf besar dan kecil apapun.
Namun karena file HTML akan diakses sebagai URL pada Web Browser, misal:
www.bybeeproject.com/nama_file.html 
Maka sangat disarankan mengikuti praktek yang baik penamaan URL.

                    =========== Praktek Baik Penamaan File HTML ===============
1) Jangan menggunakan huruf besarm selalu gunakan huruf kecil semua. Contoh:
index.html home.html wafi.html dll.
2) Jangan menggunakan nama spasi pada nama file. Jika butuh pemisah maka gunakan - atau _. Contoh:
belajar-html.html belajar_html.html halaman-login.html halaman_dashboard.html
3) Jika butuh membuat folder, gunakan kedua aturan tersebut.

