                    =========== Break Line ===============
Seperti yang dibahas di materi Paragraph, enter di dalam tulisan tidak akan dianggap enter oleh HTML. 
Jika kita ingin membuat enter, disarankan membuat paragraf terpisah.
Namun, jika kita benar-benar ingin membuat enter di dalam paragraf, kita dapat menggunakan tag br.
Tag br merupakan void element, jadi tidak memiliki konten atau isi di dalam tag tersebut.

Contoh kode:
<html>
    <body>
        <h1>Belajar HTML</h1>
        <p>Ini adalah paragraf
            <br>
            Ini adalah baris selanjutnya setelah tag br
        </p>
    </body>
</html>

                    =========== Horizontal Rule ===============
Di HTML, kita juga dapat membuat enter dengan garis horizontal (dari kiri ke kanan) sebagai pemisah.
Untuk melakukannya, kita dapat menggunakan tag hr.
Tag hr juga merupakan void element, yang tidak memiliki konten atau isi di dalam tag tersebut.

contoh kode:
<html>
    <body>
        <h1>Belajar HTML</h1>
        <p>Ini adalah paragraf
            <br>
            Ini adalah baris selanjutnya setelah tag br
            <hr>
            Ini adalah baris selanjutnya setelah tag hr dengan horizontal rule
        </p>
    </body>
</html>