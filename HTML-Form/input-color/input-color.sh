                    =========== Input Color ===============
Input type color merupakan type untuk menerima input warna.
Warna di HTML akan ditulis dalam bentuk hex code.
Contoh daftar hex code warna dapat dilihat di link berikut:
https://www.color-hex.com/

Contoh penerapan kode:
<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>Belajar HTML Form - Input Color</title>
</head>
<body>
    <h1><b>Belajar HTML Form - Input Color</b></h1>

    <form>

        <!--Tag label-->
        <label for="favourite">My Favourite Color: </label>
        <!--Tag input dengan type=color name=favourite id=favourite dan value=#ff0000-->
        <input type="color" name="favourite" id="favourite" value="ff0000">

    </form>
</body>
</html>