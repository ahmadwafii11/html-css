                    =========== Pseudo-classes Selector ===============
Pseudo-classes Selector merupakan kata kunci yang ditambahkan ke selector yang merepresentasikan state / keadaan tertentu dari element yang diseleksi.
Untuk menambahkan pseudo-classes, kita dapat menggunakan : (titik dua).
Kita dapat melihat daftar pseudo-classes yang tersedia melalui link berikut:
https://developer.mozilla.org/en-US/docs/Web/CSS/Pseudo-classes

Contoh kode:
button:hover{
    color: blue;
}