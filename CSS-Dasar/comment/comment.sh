                    =========== Comment ===============
Saat membuat kode CSS, terkadang kita ingin menyisipkan beberapa komentar.
Komentar merupakan kode yangh tidak akan berdampak apapun. 
Untuk membuat komentar, kita harus mengawali dengan /* dan diakhiri dengan */.
komentar dapat multi baris.

Contoh penerapan kode:
/*Ini merupakan komentar satu baris*/
h1 {
    color: red;
    font-size: 10px;
}

/* Ini merupakan 
komentar muli baris*/

h2 {
    color: yellow;
    font-size: 20px;
}