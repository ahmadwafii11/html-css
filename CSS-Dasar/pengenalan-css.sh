                    =========== Pengenalan CSS ===============
CSS merupakan singkatan dari Cascading Style Sheets.
HTML digunakan untuk membuat struktur konten web secara semantic, dan CSS digunakan untuk memberi style (gaya) dan layout (tata letak) pada konten HTML.
Contohnya, kita dapat menggunakan CSS untuk mengubah font, color, size, dll. pada konten yang sudah kita buat menggunakan HTML.

                    =========== Apa itu CSS? ===============
CSS merupakan bahasa yang dapat digunakan untuk mendeskripsikan bagaimana sebuah dokumen yang sudah dibuat menggunakan HTML ditampilkan ke pengguna web.
Setiap browser biasanya masing-masing memiliki standar ketika menampilkan kode HTML.
Dengan menggunakan CSS, kita dapat membuat semua browser menampilkan dokumen HTML dengan cara yang sama.

                    =========== CSS Syntax ===============
CSS merupakan bahasa yang berbaris rule / aturan.
Kita akan mendefinisikan rule / aturan untuk element yang terdapat di dokumen HTML yang akan kita buat.
Membuat rule di CSS biasanya dimulai dengan menyebutkan element yang akan dipilih, lalu diikuti dengan kurung kurawal buka, dilanjutkan dengan aturan-aturan yang akan kita gunakan, dan diakhiri dengan kurung kurawal tutup.
Aturan dalam CSS disebutkan dengan
property: value;

Contoh penerapan kode CSS:
h1 {
    color: red;
    font-size: 20px
}

h2{
    color: blue;
    font-size: 15px;
}