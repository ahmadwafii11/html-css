                     =========== Debug dengan Browser ===============
Salah satu cara saat kita ingin melihat Box Model pada halaman HTML yaitu dengan menggunakan Web Browser.
Tiap Web Browser biasanya terdapat fitur untuk melihat detail dari informasi halaman HTML yang sedang dibuka.
Contohnya, di Google Chrome, kita dapat klik kanan element yang ingin kita lihat, lalu pilih menu Inspect Element.