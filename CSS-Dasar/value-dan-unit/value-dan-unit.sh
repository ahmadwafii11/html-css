                     =========== Value dan Unit ===============
Saat kita menggunakan CSS, kita sering kali meggunakan berbagai jenis value, dimulai dari number, text, color name, rgb, image, dll.
Semua standarisasi dari CSS Value dan Unit sudah ditetapkan pada spesifikasi berikut:
https://drafts.csswg.org/css-values/

                     =========== Length ===============
Salah satu value yang penting kita untuk mengerti adalah Value Length.
Sebelumnya kita sering menggunakan px untuk piksel, selain px masih terdapat banyak type yang dapat kita gunakan.
Lengkapnya:
https://developer.mozilla.org/en-US/docs/Web/CSS/length